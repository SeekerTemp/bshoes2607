    //valid
    private boolean isValidEmail(String email) {
    return email.matches(".+@.+\\..+");
}


// Kiểm tra SDT phải là đúng 10 số
    private boolean isValidPhone(String sdt) {
    return sdt.matches("\\d{10}");
    }
    @Override
    public void create() {
        KhachHang kh = getForm();
        
        

// kiểm tra email
        if (!isValidEmail(kh.getEmail())) {
            JOptionPane.showMessageDialog(this, "Email không hợp lệ phải có @!");
            return;
        }

// kiểm tra số điện thoại
        if (!isValidPhone(kh.getSo_dien_thoai())) {
            JOptionPane.showMessageDialog(this, "Số điện thoại phải đúng 10 số!");
            return;
        }

// kiểm tra trùng
        if (repoKH.existsMa(kh.getMa_khach_hang())) {
            JOptionPane.showMessageDialog(this, "Mã khách hàng đã tồn tại!");
            return;
        }

        if (repoKH.existsEmail(kh.getEmail())) {
            JOptionPane.showMessageDialog(this, "Email đã tồn tại!");
            return;
        }

        if (repoKH.existsSDT(kh.getSo_dien_thoai())) {
            JOptionPane.showMessageDialog(this, "Số điện thoại đã tồn tại!");
            return;
        }
        
        try {
        repoKH.create(kh);
        fillToTable();
        JOptionPane.showMessageDialog(this, "Thêm thành công!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Lỗi thêm dữ liệu!");
    }

        //throw new UnsupportedOperationException("Not supported yet."); // Generated from nbfs://nbhost/SystemFileSystem/Templates/Classes/Code/GeneratedMethodBody
    }

