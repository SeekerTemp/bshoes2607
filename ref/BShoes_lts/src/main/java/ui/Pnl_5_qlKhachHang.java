        model.setRowCount(0);
        for (KhachHang kh : repoKH.findByName(name)){
        model.addRow(new Object[]{
            kh.getId_khach_hang(),
            kh.getMa_khach_hang(),
            kh.getTen_khach_hang(),
            kh.getGioi_tinh(),
            kh.getSo_dien_thoai(),
            kh.getDia_chi(),
            kh.getEmail(),
            kh.isTrang_thai(),
        });
    }
