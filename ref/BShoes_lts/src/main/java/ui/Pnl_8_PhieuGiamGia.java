    @Override
    public PhieuGiamGia getForm() {
        PhieuGiamGia pgg = new PhieuGiamGia();
        pgg.setMa_phieu_giam(txt_ma.getText());
        pgg.setTen_phieu_giam(txt_ten.getText());
        int loai = cbo_loaiGiamGia.getSelectedIndex();
        pgg.setLoai_giam_gia(loai);
        pgg.setGia_tri_giam(new BigDecimal(txt_mucGiam.getText()));
        pgg.setDon_toi_thieu(new BigDecimal(txt_donToiThieu.getText()));
        pgg.setGiam_toi_da(new BigDecimal(txt_giamToiDa.getText()));
        pgg.setSo_luong(Integer.parseInt(txt_soLuong.getText()));
        if (date_PickerStart.getDate() !=null) {
            pgg.setThoi_gian_bat_dau(
            Timestamp.valueOf(date_PickerStart.getDate().atStartOfDay()));
        }
        if (date_PickerEnd.getDate() !=null) {
            pgg.setThoi_gian_ket_thuc(
            Timestamp.valueOf(date_PickerEnd.getDate().atStartOfDay()));
 
        }
        if (rdo_HD.isSelected()) {
        pgg.setTrang_thai(true);   
        } else {
            pgg.setTrang_thai(false); 
        }
        return pgg;
    }

