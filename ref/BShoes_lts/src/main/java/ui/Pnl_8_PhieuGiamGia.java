    @Override
    public void edit() {
    int row = tbl_phieuGG.getSelectedRow();

    int id = (int) tbl_phieuGG.getValueAt(row, 0);

    PhieuGiamGia x = repoPGG.findById(id);

    txt_ma.setText(x.getMa_phieu_giam());
    txt_ten.setText(x.getTen_phieu_giam());

    if (x.getLoai_giam_gia() == 0) {
        cbo_loaiGiamGia.setSelectedItem("Giảm theo %");
    } else {
        cbo_loaiGiamGia.setSelectedItem("Giảm theo số tiền");
    }

    txt_mucGiam.setText(String.valueOf(x.getGia_tri_giam()));
    txt_donToiThieu.setText(String.valueOf(x.getDon_toi_thieu()));
    txt_giamToiDa.setText(String.valueOf(x.getGiam_toi_da()));
    txt_soLuong.setText(String.valueOf(x.getSo_luong()));

    if (x.getThoi_gian_bat_dau() != null) {
        LocalDate start = x.getThoi_gian_bat_dau().toLocalDateTime().toLocalDate();
        date_PickerStart.setDate(start);
    }

    if (x.getThoi_gian_ket_thuc() != null) {
        LocalDate end = x.getThoi_gian_ket_thuc().toLocalDateTime().toLocalDate();
        date_PickerEnd.setDate(end);
    }


    if (x.isTrang_thai()) {
        rdo_HD.setSelected(true);
    } else {
        rdo_khongHD.setSelected(true);
    }
}
    
    
    private boolean validateDuplicate() {
    String ma = txt_ma.getText().trim();
    String ten = txt_ten.getText().trim();

    if (repoPGG.existsMa(ma)) {
        JOptionPane.showMessageDialog(this, "Mã phiếu đã tồn tại!");
        return false;
    }
    if (repoPGG.existsTen(ten)) {
        JOptionPane.showMessageDialog(this, "Tên phiếu đã tồn tại!");
        return false;
    }
    return true;
}
    
    
    

    @Override
    public void create() {
        if (!validateDuplicate()) return; // nếu trùng thì dừng ngay
        
    try {
        repoPGG.create(getForm());
        fillToTable();
        JOptionPane.showMessageDialog(this, "Thêm thành công!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Lỗi thêm!");
    }
    }
    
    
    
    private boolean validateDuplicateUpdate(int id) {
    String ma = txt_ma.getText().trim();
    String ten = txt_ten.getText().trim();

    PhieuGiamGia old = repoPGG.findById(id);

    if (!ma.equals(old.getMa_phieu_giam()) && repoPGG.existsMa(ma)) {
        JOptionPane.showMessageDialog(this, "Mã phiếu đã tồn tại!");
        return false;
    }
    if (!ten.equals(old.getTen_phieu_giam()) && repoPGG.existsTen(ten)) {
        JOptionPane.showMessageDialog(this, "Tên phiếu đã tồn tại!");
        return false;
    }
    return true;
}
    
    
    

    @Override
    public void update() {
    int row = tbl_phieuGG.getSelectedRow();
    int id = Integer.parseInt(tbl_phieuGG.getValueAt(row, 0).toString());

    if (!validateDuplicateUpdate(id)) return;
        
    try {
        repoPGG.update(getForm());
        fillToTable();
        JOptionPane.showMessageDialog(this, "Sửa thành công!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Lỗi sửa!");
    }
    }

    @Override
    public void delete() {
        int row = tbl_phieuGG.getSelectedRow();
        int id = Integer.parseInt(tbl_phieuGG.getValueAt(row, 0).toString());
        repoPGG.deleteById(id);
        this.fillToTable();
        JOptionPane.showMessageDialog(this, "Xoá thành công!");
    }

